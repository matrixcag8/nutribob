NUTRIENTS = {"1079": "fiber", "1063": "sugars", "1258": "satFat", "1087": "calcium", "1089": "iron",
             "1090": "magnesium", "1092": "potassium", "1093": "sodium", "1095": "zinc", "1106": "vitA",
             "1162": "vitC", "1114": "vitD", "1178": "vitB12", "1177": "folate"}

if __name__ == "__main__":
    ids = {str(i) for i in FDC.values()}
    values: dict[str, dict[str, float]] = {}
    with open(Path(sys.argv[1]) / "food_nutrient.csv") as f:
        for r in csv.DictReader(f):
            if r["fdc_id"] in ids and r["nutrient_id"] in NUTRIENTS:
                values.setdefault(r["fdc_id"], {})[NUTRIENTS[r["nutrient_id"]]] = round(float(r["amount"]), 2)
    out = {name: values[str(i)] for name, i in FDC.items() if str(i) in values}
    assert len(out) == len(FDC), set(FDC) - set(out)
    (Path(__file__).parent / "micros.json").write_text(json.dumps(out, ensure_ascii=False, indent=0, sort_keys=True))
    print(f"{len(out)} alimenti con micronutrienti")
